const OUTLINE = "#0b0618";

const hex = c => [1, 3, 5].map(i => parseInt(c.slice(i, i + 2), 16));
const shade = (c, f) => `rgb(${hex(c).map(v => Math.round(f > 1 ? v + (255 - v) * (f - 1) : v * f)).join(",")})`;

const cache = new Map();

/** The kit's 24x24 portrait canvas (cached). */
export function fighterSprite(kit) {
    if (cache.has(kit)) return cache.get(kit);
    const k = PALETTES[kit] ? kit : "none";
    const pal = { ...SHARED, ...PALETTES[k] };
    const grid = Array.from({ length: SPRITE_H }, () => Array(SPRITE_W).fill(null));
    const paint = layer => layer.forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== ".") grid[y][x] = pal[ch] ?? pal.S; }));
    if (k === "pepf") paint(CAPE);
    paint(BODY);
    paint(FACE);
    paint(HATS[k]);
    paint(GEAR[k]);
    const canvas = document.createElement("canvas");
    canvas.width = SPRITE_W;
    canvas.height = SPRITE_H;
    const ctx = canvas.getContext("2d");
    const filled = (x, y) => x >= 0 && y >= 0 && x < SPRITE_W && y < SPRITE_H && grid[y][x];
    for (let y = 0; y < SPRITE_H; y++) for (let x = 0; x < SPRITE_W; x++) {
        const c = grid[y][x];
        if (!c) {
            // Outline: empty pixels touching the sprite.
            if (filled(x - 1, y) || filled(x + 1, y) || filled(x, y - 1) || filled(x, y + 1)) { ctx.fillStyle = OUTLINE; ctx.fillRect(x, y, 1, 1); }
            continue;
        }
        // Rim light from the upper left, shadow on the lower right edges.
        let f = 1;
        if (!filled(x - 1, y) || !filled(x, y - 1)) f = 1.18;
        else if (!filled(x + 1, y) || !filled(x, y + 1)) f = 0.78;
        ctx.fillStyle = c.startsWith("#") && f !== 1 ? shade(c, f) : c;
        ctx.fillRect(x, y, 1, 1);
    }
    cache.set(kit, canvas);
    return canvas;
}

/** A crisp, upscaled portrait for the DOM (kit cards, lobby, podium). */
const portraits = new Map();
export function portraitUrl(kit, scale = 4) {
    const key = `${kit}|${scale}`;
    if (portraits.has(key)) return portraits.get(key);
    const src = fighterSprite(kit);
    const c = document.createElement("canvas");
    c.width = SPRITE_W * scale;
    c.height = SPRITE_H * scale;
    const ctx = c.getContext("2d");
    ctx.imageSmoothingEnabled = false;
    ctx.drawImage(src, 0, 0, c.width, c.height);
    const url = c.toDataURL();
    portraits.set(key, url);
    return url;
}

const images = new Map();
/** Loads (and caches) an image; returns it even before it finished loading. */
export function image(src) {
    if (!images.has(src)) {
        const img = new Image();
        img.src = src;
        images.set(src, img);
    }
    return images.get(src);
}
